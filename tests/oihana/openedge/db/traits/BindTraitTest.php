<?php

namespace tests\oihana\openedge\db\traits;

use oihana\exceptions\BindException;
use oihana\openedge\db\traits\BindTrait;
use oihana\openedge\enums\OpenEdge;
use PHPUnit\Framework\TestCase;

final class BindTraitTest extends TestCase
{
    private object $query;

    protected function setUp(): void
    {
        $this->query = new class {
            use BindTrait;
        };
        $this->query->initializeQueryID( 'q' );
    }

    public function testBindWithExplicitNameStoresValueAndReturnsPrefixed(): void
    {
        $binds = [];
        $expr  = $this->query->bind( 'hello', $binds, 'my_var' );

        $this->assertSame( ':my_var', $expr );
        $this->assertSame( [ 'my_var' => 'hello' ], $binds );
    }

    public function testBindWithNullPrefixReturnsBareName(): void
    {
        $binds = [];
        $expr  = $this->query->bind( 42, $binds, 'my_var', null );

        $this->assertSame( 'my_var', $expr );
        $this->assertSame( [ 'my_var' => 42 ], $binds );
    }

    public function testBindWithAutoGeneratedNameFollowsQueryIdPattern(): void
    {
        $binds = [];
        $expr  = $this->query->bind( 'x', $binds );

        $this->assertMatchesRegularExpression( '/^:q_\d+$/', $expr );
        $this->assertCount( 1, $binds );
    }

    public function testToBindExpressionWrapsInBindKey(): void
    {
        $binds = [];
        $result = $this->query->toBindExpression( 'v', $binds, 'my_var' );

        $this->assertSame( [ OpenEdge::BIND => 'my_var' ], $result );
        $this->assertSame( [ 'my_var' => 'v' ], $binds );
    }

    public function testInvalidBindNameThrows(): void
    {
        $binds = [];
        $this->expectException( BindException::class );
        $this->query->bind( 'v', $binds, 'bad name' );
    }

    public function testIsBindParameterAcceptsColonPrefixed(): void
    {
        $this->assertTrue( $this->query->isBindParameter( ':foo' ) );
        $this->assertTrue( $this->query->isBindParameter( 'foo123' ) );
    }

    public function testIsBindParameterRejectsInvalid(): void
    {
        $this->assertFalse( $this->query->isBindParameter( 'foo-bar' ) );
        $this->assertFalse( $this->query->isBindParameter( '_leading' ) );
    }

    public function testIsBindParameterWithCustomPrefix(): void
    {
        $this->assertTrue( $this->query->isBindParameter( '@foo', '@' ) );
    }
}
